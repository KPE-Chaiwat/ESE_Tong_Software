#!/usr/bin/env node
// Generates TypeScript bindings from the Rust DTOs in crates/shared-types via ts-rs.
//
//   node scripts/gen-bindings.mjs           regenerate apps/desktop/src/shared/bindings/
//   node scripts/gen-bindings.mjs --check   regenerate into a temp dir and fail (exit 1)
//                                           if the committed bindings differ (for CI)
//
// ts-rs writes the files while running the `export_bindings_*` tests it derives for every
// `#[ts(export)]` type, into the directory given by the TS_RS_EXPORT_DIR environment variable.

import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const bindingsDir = join(root, "apps", "desktop", "src", "shared", "bindings");
const check = process.argv.includes("--check");

/** Remove every generated .ts file so deleted Rust types do not leave stale bindings behind. */
function clean(dir) {
  mkdirSync(dir, { recursive: true });
  for (const f of readdirSync(dir)) {
    if (f.endsWith(".ts")) rmSync(join(dir, f));
  }
}

function generate(outDir) {
  clean(outDir);
  const result = spawnSync(
    "cargo",
    ["test", "--workspace", "--lib", "export_bindings", "--quiet"],
    { cwd: root, stdio: "inherit", env: { ...process.env, TS_RS_EXPORT_DIR: outDir } },
  );
  if (result.error) throw result.error;
  if (result.status !== 0) {
    console.error("bindings: `cargo test` failed while exporting ts-rs types");
    process.exit(result.status ?? 1);
  }
  for (const f of readdirSync(outDir).filter((name) => name.endsWith(".ts"))) {
    const path = join(outDir, f);
    writeFileSync(path, readFileSync(path, "utf8").replace(/[\t ]+$/gm, ""));
  }
  // Barrel file so the frontend imports from "@/shared/bindings".
  const types = readdirSync(outDir)
    .filter((f) => f.endsWith(".ts") && f !== "index.ts")
    .map((f) => f.slice(0, -3))
    .sort();
  const barrel = [
    "// This file is generated by scripts/gen-bindings.mjs. Do not edit it by hand.",
    ...types.map((t) => `export type { ${t} } from "./${t}";`),
    "",
  ].join("\n");
  writeFileSync(join(outDir, "index.ts"), barrel);
}

function readAll(dir) {
  const files = new Map();
  for (const f of readdirSync(dir).filter((n) => n.endsWith(".ts"))) {
    files.set(f, readFileSync(join(dir, f), "utf8").replace(/\r\n/g, "\n"));
  }
  return files;
}

if (!check) {
  generate(bindingsDir);
  console.log(`bindings: generated into ${bindingsDir}`);
} else {
  const tmp = mkdtempSync(join(tmpdir(), "esefact-bindings-"));
  try {
    generate(tmp);
    mkdirSync(bindingsDir, { recursive: true });
    const fresh = readAll(tmp);
    const committed = readAll(bindingsDir);
    const problems = [];
    for (const [name, content] of fresh) {
      if (!committed.has(name)) problems.push(`missing: ${name}`);
      else if (committed.get(name) !== content) problems.push(`stale:   ${name}`);
    }
    for (const name of committed.keys()) {
      if (!fresh.has(name)) problems.push(`orphan:  ${name}`);
    }
    if (problems.length > 0) {
      console.error("bindings: out of date. Run `pnpm bindings` and commit the result.");
      for (const p of problems) console.error(`  ${p}`);
      process.exit(1);
    }
    console.log(`bindings: up to date (${fresh.size} files)`);
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}
